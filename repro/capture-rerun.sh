#!/usr/bin/env bash
# Cold kind cluster from repro/kind-config.yaml, then a full ./run-kind.sh
# and a ./run-kind.sh --checks-only. Captures land in cluster-logs/v0.20.3-rerun.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
export OUT=${OUT:-$ROOT/cluster-logs/v0.20.3-rerun}
export KUEUE_VERSION=${KUEUE_VERSION:-v0.20.3}
export CLUSTER=${CLUSTER:-kueue-fs}
# shellcheck source=capture-header.sh
source "$HERE/capture-header.sh"
rm -rf "$OUT"
mkdir -p "$OUT/setup"
if [ -S /var/run/docker.sock ]; then
  chmod 666 /var/run/docker.sock 2>/dev/null || sudo chmod 666 /var/run/docker.sock || true
fi
refresh_header_versions || true
cd "$ROOT"

if kind get clusters 2>/dev/null | grep -qx "$CLUSTER"; then
  run_cap "$OUT/setup/kind-delete.txt" -- kind delete cluster --name "$CLUSTER"
fi
# Readers run this from the repo root. The config path is the file named in the README.
run_cap "$OUT/setup/kind-create.txt" -- kind create cluster --config repro/kind-config.yaml
if ! kind get clusters 2>/dev/null | grep -qx "$CLUSTER"; then
  CAPTURE_FIRST_LINE='DERIVED (generated by repro/capture-rerun.sh from raw output)'
  write_header "$OUT/setup/KIND-CREATE-FAILED.txt" "kind create cluster --config repro/kind-config.yaml" "note: the cluster was not created. Scenario captures were not run. kind-create.txt holds the command output." "exit_code: 1"
  unset CAPTURE_FIRST_LINE
  echo "kind create did not leave a cluster named ${CLUSTER}" >> "$OUT/setup/KIND-CREATE-FAILED.txt"
  python3 "$HERE/write-rerun-index.py" "$OUT" || true
  exit 1
fi
kubectl config use-context "kind-${CLUSTER}" >/dev/null
refresh_header_versions || true
run_cap "$OUT/setup/current-context.txt" -- kubectl config current-context
run_cap "$OUT/setup/kube-proxy-configmap.yaml" -- kubectl -n kube-system get cm kube-proxy -o yaml
run_cap "$OUT/setup/kind-version.txt" -- kind version
run_cap "$OUT/setup/kubectl-version.txt" -- kubectl version
run_cap "$OUT/setup/node-image.txt" -- docker inspect "${CLUSTER}-control-plane" --format '{{.Config.Image}}'
run_cap "$OUT/setup/node-json.txt" -- docker inspect "${CLUSTER}-control-plane" --format '{{json .Config.Image}} {{json .Image}}'
run_cap "$OUT/setup/nodes-wide.txt" -- kubectl get nodes -o wide
resolve_kueue_commit || true
refresh_header_versions || true

write_header "$OUT/setup/run-kind.txt" "./run-kind.sh" "cwd: ${HERE}" "OUT: ${OUT}" "note: exit_code trailer below the body is the shell status recorded by capture-rerun.sh, not a line printed by run-kind.sh"
set +e
( cd "$HERE" && OUT="$OUT" ./run-kind.sh ) >> "$OUT/setup/run-kind.txt" 2>&1
rc=$?
set -e
{
  echo "===== shell status ====="
  echo "exit_code: ${rc}"
} >> "$OUT/setup/run-kind.txt"
CAPTURE_FIRST_LINE='DERIVED (generated by repro/capture-rerun.sh from raw output)'
write_header "$OUT/setup/run-kind.exit.txt" "shell status of ./run-kind.sh recorded by capture-rerun.sh" "label: DERIVED" "exit_code: ${rc}"
unset CAPTURE_FIRST_LINE
echo "${rc}" >> "$OUT/setup/run-kind.exit.txt"

mkdir -p "$OUT/full-run"
if [ -d "$OUT/requeue" ]; then
  rm -rf "$OUT/full-run/requeue"
  cp -a "$OUT/requeue" "$OUT/full-run/requeue"
fi
if [ -d "$OUT/grace" ]; then
  rm -rf "$OUT/full-run/grace"
  cp -a "$OUT/grace" "$OUT/full-run/grace"
fi
if [ -f "$OUT/SUMMARY.txt" ]; then
  cp -a "$OUT/SUMMARY.txt" "$OUT/full-run/SUMMARY.txt"
fi

write_header "$OUT/setup/run-kind-checks-only.txt" "./run-kind.sh --checks-only" "cwd: ${HERE}" "OUT: ${OUT}" "note: exit_code trailer below the body is the shell status recorded by capture-rerun.sh, not a line printed by run-kind.sh"
set +e
( cd "$HERE" && OUT="$OUT" ./run-kind.sh --checks-only ) >> "$OUT/setup/run-kind-checks-only.txt" 2>&1
rc2=$?
set -e
{
  echo "===== shell status ====="
  echo "exit_code: ${rc2}"
} >> "$OUT/setup/run-kind-checks-only.txt"
CAPTURE_FIRST_LINE='DERIVED (generated by repro/capture-rerun.sh from raw output)'
write_header "$OUT/setup/run-kind-checks-only.exit.txt" "shell status of ./run-kind.sh --checks-only recorded by capture-rerun.sh" "label: DERIVED" "exit_code: ${rc2}"
unset CAPTURE_FIRST_LINE
echo "${rc2}" >> "$OUT/setup/run-kind-checks-only.exit.txt"

python3 "$HERE/write-rerun-index.py" "$OUT" || true
echo "full_exit=${rc} checks_only_exit=${rc2}"
exit 0
