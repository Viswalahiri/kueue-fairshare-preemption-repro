#!/usr/bin/env python3
"""Write cluster-logs/v0.20.3-rerun/INDEX.md from the capture files on disk."""

from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

BODY_MARK = "===== capture body ====="


def header_fields(path: Path) -> dict[str, str]:
    fields: dict[str, str] = {}
    try:
        text = path.read_text(errors="replace")
    except OSError as exc:
        return {"read_error": str(exc)}
    for line in text.splitlines():
        if line.strip() == BODY_MARK:
            break
        if ":" in line and not line.startswith(" "):
            key, value = line.split(":", 1)
            fields.setdefault(key.strip(), value.strip())
    return fields


def origin(path: Path, fields: dict[str, str]) -> str:
    rel = path.as_posix()
    src = fields.get("source", "")
    if "unit test" in src or rel.startswith("unit/"):
        base = "unit test"
    else:
        base = "live kind"
    if fields.get("label") == "DERIVED":
        return base + " (derived by the capture script, not raw command output)"
    return base


def main() -> None:
    root = Path(sys.argv[1]).resolve()
    rows = []
    for path in sorted(p for p in root.rglob("*") if p.is_file() and p.name != "INDEX.md"):
        rel = path.relative_to(root).as_posix()
        fields = header_fields(path)
        rows.append(
            (
                rel,
                fields.get("date", ""),
                origin(path.relative_to(root), fields),
                fields.get("command", ""),
            )
        )
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "DERIVED (generated by repro/write-rerun-index.py from raw output)",
        "",
        "# cluster-logs/v0.20.3-rerun",
        "",
        f"Index generated by `repro/write-rerun-index.py` at {now}.",
        "Origin is `live kind` or `unit test` for files in this directory. Files under `unit/` are the put-back Go test. Everything else in this directory was captured on the kind cluster `kueue-fs` during this re-run.",
        "A derived file starts with `DERIVED (generated by <script> from raw output)`. Its body was produced by that script from live command output. Raw files start with `date:` and the bytes after `===== capture body =====` are the command stdout. `SUMMARY (hand-written, not raw output)` is only for files that were written by hand.",
        "",
        "| File | Header date (UTC) | Origin | Command |",
        "|---|---|---|---|",
    ]
    for rel, date, src, cmd in rows:
        cmd_cell = cmd.replace("|", "\\|").replace("`", "'")
        lines.append(f"| `{rel}` | {date} | {src} | `{cmd_cell}` |")
    lines.append("")
    lines.append(f"File count: {len(rows)}")
    lines.append("")
    lines.extend(original_run_section(root))
    (root / "INDEX.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {root / 'INDEX.md'} ({len(rows)} files)")


def original_run_section(rerun_root: Path) -> list[str]:
    """Pod lists copied from the 2026-10-25 session. Not part of this re-run."""
    repo = Path(__file__).resolve().parent.parent
    orig = repo / "cluster-logs/v0.20.3/grace/original-run-transcript"
    # Command recorded next to this tool result in the 2026-10-25 session transcript.
    commands = {
        "run2-victim-about-28s-and-run3-pods-wide.txt": "kubectl --context kind-kueue-fs get pods -A -o wide | head -40",
    }
    lines = [
        "## Original run, kept separate from this re-run",
        "",
        "Files under `cluster-logs/v0.20.3/grace/original-run-transcript/`.",
        "Each file's first line is `Copied verbatim from the original run's command output (session of 2026-10-25); not re-captured.`",
        "The bytes after that line are the original session's command output. They were not captured again on this re-run.",
        "Origin for each of these files is `original-run, live kind`.",
        "",
        "| File | Session date | Origin | Command |",
        "|---|---|---|---|",
    ]
    if not orig.is_dir():
        lines.append("| (directory missing) | | original-run, live kind | |")
        lines.append("")
        return lines
    files = sorted(p for p in orig.iterdir() if p.is_file() and p.name != "INDEX.md")
    for path in files:
        rel = path.relative_to(repo).as_posix()
        cmd = commands.get(path.name, "")
        cmd_cell = cmd.replace("|", "\\|").replace("`", "'")
        lines.append(f"| `{rel}` | 2026-10-25 | original-run, live kind | `{cmd_cell}` |")
    lines.append("")
    lines.append(f"Original-run file count: {len(files)}")
    lines.append("")
    return lines


if __name__ == "__main__":
    main()
